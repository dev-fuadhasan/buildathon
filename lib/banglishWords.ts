// Create a Set for fast lookup
export const BANGLISH_WORD_SET = new Set(
  ALL_BANGLISH_WORDS.map(word => word.toLowerCase())
);

/**
 * Check if a word is a Banglish word
 */
export function isBanglishWord(word: string): boolean {
  return BANGLISH_WORD_SET.has(word.toLowerCase());
}

/**
 * Calculate Banglish score for a text
 * Returns percentage of Banglish words (0-100)
 */
export function getBanglishScore(text: string): number {
  const words = text
    .toLowerCase()
    .replace(/[^\w\s]/g, " ")
    .split(/\s+/)
    .filter(w => w.length > 1);
  
  if (words.length === 0) return 0;
  
  const banglishCount = words.filter(word => isBanglishWord(word)).length;
  return Math.round((banglishCount / words.length) * 100);
}

/**
 * Check if text is predominantly Banglish (>20% Banglish words)
 */
export function isBanglishText(text: string): boolean {
  return getBanglishScore(text) > 20;
}

